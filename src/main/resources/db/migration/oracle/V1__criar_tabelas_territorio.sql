-- [Oracle] V1: territorio - setores de risco, pontos de apoio e moradores

CREATE TABLE TB_AE_SETOR (
    ID_SETOR                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CD_SETOR                 VARCHAR2(10 CHAR)  NOT NULL,
    NM_SETOR                 VARCHAR2(100 CHAR) NOT NULL,
    NM_BAIRRO                VARCHAR2(80 CHAR)  NOT NULL,
    DS_TIPO_RISCO            VARCHAR2(15 CHAR)  NOT NULL,
    DS_NIVEL_RISCO           VARCHAR2(10 CHAR)  NOT NULL,
    NR_LATITUDE              NUMBER(9,6) NOT NULL,
    NR_LONGITUDE             NUMBER(9,6) NOT NULL,
    NR_LIMITE_CHUVA_MM       NUMBER(6,2) NOT NULL,
    NR_LIMITE_UMIDADE_PCT    NUMBER(5,2) NOT NULL,
    NR_LIMITE_NIVEL_AGUA_CM  NUMBER(6,2),
    DT_ATUALIZACAO_RISCO     TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_AE_SETOR PRIMARY KEY (ID_SETOR),
    CONSTRAINT UK_AE_SETOR_CODIGO UNIQUE (CD_SETOR),
    CONSTRAINT CK_AE_SETOR_TIPO CHECK (DS_TIPO_RISCO IN ('DESLIZAMENTO', 'ALAGAMENTO', 'MISTO')),
    CONSTRAINT CK_AE_SETOR_NIVEL CHECK (DS_NIVEL_RISCO IN ('BAIXO', 'MEDIO', 'ALTO')),
    CONSTRAINT CK_AE_SETOR_LIMITES CHECK (NR_LIMITE_CHUVA_MM > 0 AND NR_LIMITE_UMIDADE_PCT > 0 AND NR_LIMITE_UMIDADE_PCT <= 100)
);

CREATE TABLE TB_AE_PONTO_APOIO (
    ID_PONTO_APOIO  NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_PONTO_APOIO  VARCHAR2(120 CHAR) NOT NULL,
    DS_TIPO         VARCHAR2(20 CHAR)  NOT NULL,
    DS_ENDERECO     VARCHAR2(200 CHAR) NOT NULL,
    NR_LATITUDE     NUMBER(9,6) NOT NULL,
    NR_LONGITUDE    NUMBER(9,6) NOT NULL,
    NR_CAPACIDADE   NUMBER(10)      NOT NULL,
    DS_SITUACAO     VARCHAR2(10 CHAR)  NOT NULL,
    CONSTRAINT PK_AE_PONTO_APOIO PRIMARY KEY (ID_PONTO_APOIO),
    CONSTRAINT CK_AE_PONTO_TIPO CHECK (DS_TIPO IN ('ESCOLA', 'IGREJA', 'CENTRO_COMUNITARIO', 'UBS', 'OUTRO')),
    CONSTRAINT CK_AE_PONTO_SITUACAO CHECK (DS_SITUACAO IN ('ATIVO', 'INATIVO')),
    CONSTRAINT CK_AE_PONTO_CAPACIDADE CHECK (NR_CAPACIDADE > 0)
);

CREATE TABLE TB_AE_MORADOR (
    ID_MORADOR               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_MORADOR               VARCHAR2(120 CHAR) NOT NULL,
    DS_EMAIL                 VARCHAR2(150 CHAR) NOT NULL,
    NR_CPF                   VARCHAR2(11 CHAR)  NOT NULL,
    NR_TELEFONE              VARCHAR2(20 CHAR)  NOT NULL,
    DS_ENDERECO              VARCHAR2(200 CHAR) NOT NULL,
    NR_LATITUDE              NUMBER(9,6),
    NR_LONGITUDE             NUMBER(9,6),
    ID_SETOR                 NUMBER(19)       NOT NULL,
    DS_NECESSIDADE_ESPECIAL  VARCHAR2(25 CHAR)  NOT NULL,
    DS_PUSH_TOKEN            VARCHAR2(200 CHAR),
    DT_CRIACAO               TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_AE_MORADOR PRIMARY KEY (ID_MORADOR),
    CONSTRAINT UK_AE_MORADOR_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT UK_AE_MORADOR_CPF UNIQUE (NR_CPF),
    CONSTRAINT FK_AE_MORADOR_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_AE_SETOR (ID_SETOR),
    CONSTRAINT CK_AE_MORADOR_NECESSIDADE CHECK (DS_NECESSIDADE_ESPECIAL IN
        ('NENHUMA', 'IDOSO', 'MOBILIDADE_REDUZIDA', 'DEFICIENCIA_VISUAL', 'DEFICIENCIA_AUDITIVA', 'OUTRA'))
);
