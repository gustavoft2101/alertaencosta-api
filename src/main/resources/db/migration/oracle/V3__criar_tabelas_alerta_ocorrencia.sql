-- [Oracle] V3: resposta - alertas, confirmacoes dos moradores, reportes (ocorrencias) e historico

CREATE TABLE TB_AE_ALERTA (
    ID_ALERTA               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_SETOR                NUMBER(19)       NOT NULL,
    DS_NIVEL                VARCHAR2(10 CHAR)  NOT NULL,
    DS_MENSAGEM             VARCHAR2(500 CHAR) NOT NULL,
    ID_PONTO_APOIO          NUMBER(19),
    NR_DISTANCIA_METROS     NUMBER(10),
    DS_ORIGEM               VARCHAR2(12 CHAR)  NOT NULL,
    DS_STATUS               VARCHAR2(10 CHAR)  NOT NULL,
    QT_NOTIFICADOS          NUMBER(10)      DEFAULT 0 NOT NULL,
    DT_EMISSAO              TIMESTAMP(6)    NOT NULL,
    DT_ENCERRAMENTO         TIMESTAMP(6),
    DS_MOTIVO_ENCERRAMENTO  VARCHAR2(300 CHAR),
    CONSTRAINT PK_AE_ALERTA PRIMARY KEY (ID_ALERTA),
    CONSTRAINT FK_AE_ALERTA_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_AE_SETOR (ID_SETOR),
    CONSTRAINT FK_AE_ALERTA_PONTO FOREIGN KEY (ID_PONTO_APOIO) REFERENCES TB_AE_PONTO_APOIO (ID_PONTO_APOIO),
    CONSTRAINT CK_AE_ALERTA_NIVEL CHECK (DS_NIVEL IN ('MEDIO', 'ALTO')),
    CONSTRAINT CK_AE_ALERTA_ORIGEM CHECK (DS_ORIGEM IN ('AUTOMATICO', 'MANUAL')),
    CONSTRAINT CK_AE_ALERTA_STATUS CHECK (DS_STATUS IN ('ATIVO', 'ENCERRADO')),
    CONSTRAINT CK_AE_ALERTA_ENCERRAMENTO CHECK (DS_STATUS = 'ATIVO' OR DT_ENCERRAMENTO IS NOT NULL)
);

CREATE TABLE TB_AE_CONFIRMACAO (
    ID_CONFIRMACAO  NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_ALERTA       NUMBER(19)       NOT NULL,
    ID_MORADOR      NUMBER(19)       NOT NULL,
    DS_SITUACAO     VARCHAR2(15 CHAR)  NOT NULL,
    DS_OBSERVACAO   VARCHAR2(300 CHAR),
    DT_CONFIRMACAO  TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_AE_CONFIRMACAO PRIMARY KEY (ID_CONFIRMACAO),
    CONSTRAINT UK_AE_CONF_ALERTA_MORADOR UNIQUE (ID_ALERTA, ID_MORADOR),
    CONSTRAINT FK_AE_CONF_ALERTA FOREIGN KEY (ID_ALERTA) REFERENCES TB_AE_ALERTA (ID_ALERTA) ON DELETE CASCADE,
    CONSTRAINT FK_AE_CONF_MORADOR FOREIGN KEY (ID_MORADOR) REFERENCES TB_AE_MORADOR (ID_MORADOR),
    CONSTRAINT CK_AE_CONF_SITUACAO CHECK (DS_SITUACAO IN ('SEGURO', 'PRECISA_AJUDA'))
);

CREATE TABLE TB_AE_OCORRENCIA (
    ID_OCORRENCIA   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CD_PROTOCOLO    VARCHAR2(20 CHAR)   NOT NULL,
    DS_TIPO         VARCHAR2(20 CHAR)   NOT NULL,
    DS_DESCRICAO    VARCHAR2(1000 CHAR) NOT NULL,
    DS_FOTO_URL     VARCHAR2(500 CHAR),
    NR_LATITUDE     NUMBER(9,6)  NOT NULL,
    NR_LONGITUDE    NUMBER(9,6)  NOT NULL,
    DS_STATUS       VARCHAR2(15 CHAR)   NOT NULL,
    ID_MORADOR      NUMBER(19)        NOT NULL,
    ID_SETOR        NUMBER(19)        NOT NULL,
    DT_CRIACAO      TIMESTAMP(6)     NOT NULL,
    DT_ATUALIZACAO  TIMESTAMP(6)     NOT NULL,
    DT_RESOLUCAO    TIMESTAMP(6),
    CONSTRAINT PK_AE_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT UK_AE_OCORRENCIA_PROTOCOLO UNIQUE (CD_PROTOCOLO),
    CONSTRAINT FK_AE_OCORR_MORADOR FOREIGN KEY (ID_MORADOR) REFERENCES TB_AE_MORADOR (ID_MORADOR),
    CONSTRAINT FK_AE_OCORR_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_AE_SETOR (ID_SETOR),
    CONSTRAINT CK_AE_OCORR_TIPO CHECK (DS_TIPO IN ('TRINCA_PAREDE', 'TRINCA_SOLO', 'AGUA_SUBINDO', 'DESLIZAMENTO', 'QUEDA_ARVORE', 'OUTRO')),
    CONSTRAINT CK_AE_OCORR_STATUS CHECK (DS_STATUS IN ('ABERTA', 'EM_VISTORIA', 'RESOLVIDA', 'DESCARTADA'))
);

CREATE TABLE TB_AE_HISTORICO_OCORRENCIA (
    ID_HISTORICO        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_OCORRENCIA       NUMBER(19)       NOT NULL,
    DS_STATUS_ANTERIOR  VARCHAR2(15 CHAR),
    DS_STATUS_NOVO      VARCHAR2(15 CHAR)  NOT NULL,
    DS_OBSERVACAO       VARCHAR2(500 CHAR),
    DT_ALTERACAO        TIMESTAMP(6)    NOT NULL,
    CONSTRAINT PK_AE_HISTORICO PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_AE_HIST_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA)
        REFERENCES TB_AE_OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE
);
