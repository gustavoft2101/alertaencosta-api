-- V2: monitoramento - estacoes ESP32, leituras dos sensores e previsoes de risco

CREATE TABLE TB_AE_ESTACAO (
    ID_ESTACAO         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CD_ESTACAO         VARCHAR(30)  NOT NULL,
    ID_SETOR           BIGINT       NOT NULL,
    DS_SITUACAO        VARCHAR(12)  NOT NULL,
    NR_LATITUDE        DECIMAL(9,6) NOT NULL,
    NR_LONGITUDE       DECIMAL(9,6) NOT NULL,
    DT_INSTALACAO      TIMESTAMP    NOT NULL,
    DT_ULTIMA_LEITURA  TIMESTAMP,
    CONSTRAINT PK_AE_ESTACAO PRIMARY KEY (ID_ESTACAO),
    CONSTRAINT UK_AE_ESTACAO_CODIGO UNIQUE (CD_ESTACAO),
    CONSTRAINT FK_AE_ESTACAO_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_AE_SETOR (ID_SETOR),
    CONSTRAINT CK_AE_ESTACAO_SITUACAO CHECK (DS_SITUACAO IN ('ATIVA', 'MANUTENCAO', 'INATIVA'))
);

CREATE TABLE TB_AE_LEITURA (
    ID_LEITURA           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTACAO           BIGINT       NOT NULL,
    NR_CHUVA_MM          DECIMAL(6,2) NOT NULL,
    NR_UMIDADE_SOLO_PCT  DECIMAL(5,2) NOT NULL,
    NR_NIVEL_AGUA_CM     DECIMAL(6,2),
    DT_MEDICAO           TIMESTAMP    NOT NULL,
    DT_RECEBIMENTO       TIMESTAMP    NOT NULL,
    CONSTRAINT PK_AE_LEITURA PRIMARY KEY (ID_LEITURA),
    CONSTRAINT FK_AE_LEITURA_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES TB_AE_ESTACAO (ID_ESTACAO),
    CONSTRAINT CK_AE_LEITURA_FAIXAS CHECK (NR_CHUVA_MM >= 0 AND NR_UMIDADE_SOLO_PCT BETWEEN 0 AND 100
        AND (NR_NIVEL_AGUA_CM IS NULL OR NR_NIVEL_AGUA_CM >= 0))
);

CREATE TABLE TB_AE_PREVISAO (
    ID_PREVISAO       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ID_SETOR          BIGINT       NOT NULL,
    DS_NIVEL          VARCHAR(10)  NOT NULL,
    NR_PROBABILIDADE  DECIMAL(5,4),
    DS_ORIGEM         VARCHAR(15)  NOT NULL,
    DS_VERSAO_MODELO  VARCHAR(30),
    ID_LEITURA        BIGINT,
    DT_PREVISAO       TIMESTAMP    NOT NULL,
    CONSTRAINT PK_AE_PREVISAO PRIMARY KEY (ID_PREVISAO),
    CONSTRAINT FK_AE_PREVISAO_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_AE_SETOR (ID_SETOR),
    CONSTRAINT FK_AE_PREVISAO_LEITURA FOREIGN KEY (ID_LEITURA) REFERENCES TB_AE_LEITURA (ID_LEITURA),
    CONSTRAINT CK_AE_PREVISAO_NIVEL CHECK (DS_NIVEL IN ('BAIXO', 'MEDIO', 'ALTO')),
    CONSTRAINT CK_AE_PREVISAO_ORIGEM CHECK (DS_ORIGEM IN ('REGRA_LIMITES', 'MODELO_ML')),
    CONSTRAINT CK_AE_PREVISAO_PROB CHECK (NR_PROBABILIDADE IS NULL OR NR_PROBABILIDADE BETWEEN 0 AND 1)
);
