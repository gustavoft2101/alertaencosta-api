-- V1: territorio - setores de risco, pontos de apoio e moradores

CREATE TABLE TB_AE_SETOR (
    ID_SETOR                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CD_SETOR                 VARCHAR(10)  NOT NULL,
    NM_SETOR                 VARCHAR(100) NOT NULL,
    NM_BAIRRO                VARCHAR(80)  NOT NULL,
    DS_TIPO_RISCO            VARCHAR(15)  NOT NULL,
    DS_NIVEL_RISCO           VARCHAR(10)  NOT NULL,
    NR_LATITUDE              DECIMAL(9,6) NOT NULL,
    NR_LONGITUDE             DECIMAL(9,6) NOT NULL,
    NR_LIMITE_CHUVA_MM       DECIMAL(6,2) NOT NULL,
    NR_LIMITE_UMIDADE_PCT    DECIMAL(5,2) NOT NULL,
    NR_LIMITE_NIVEL_AGUA_CM  DECIMAL(6,2),
    DT_ATUALIZACAO_RISCO     TIMESTAMP    NOT NULL,
    CONSTRAINT PK_AE_SETOR PRIMARY KEY (ID_SETOR),
    CONSTRAINT UK_AE_SETOR_CODIGO UNIQUE (CD_SETOR),
    CONSTRAINT CK_AE_SETOR_TIPO CHECK (DS_TIPO_RISCO IN ('DESLIZAMENTO', 'ALAGAMENTO', 'MISTO')),
    CONSTRAINT CK_AE_SETOR_NIVEL CHECK (DS_NIVEL_RISCO IN ('BAIXO', 'MEDIO', 'ALTO')),
    CONSTRAINT CK_AE_SETOR_LIMITES CHECK (NR_LIMITE_CHUVA_MM > 0 AND NR_LIMITE_UMIDADE_PCT > 0 AND NR_LIMITE_UMIDADE_PCT <= 100)
);

CREATE TABLE TB_AE_PONTO_APOIO (
    ID_PONTO_APOIO  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NM_PONTO_APOIO  VARCHAR(120) NOT NULL,
    DS_TIPO         VARCHAR(20)  NOT NULL,
    DS_ENDERECO     VARCHAR(200) NOT NULL,
    NR_LATITUDE     DECIMAL(9,6) NOT NULL,
    NR_LONGITUDE    DECIMAL(9,6) NOT NULL,
    NR_CAPACIDADE   INTEGER      NOT NULL,
    DS_SITUACAO     VARCHAR(10)  NOT NULL,
    CONSTRAINT PK_AE_PONTO_APOIO PRIMARY KEY (ID_PONTO_APOIO),
    CONSTRAINT CK_AE_PONTO_TIPO CHECK (DS_TIPO IN ('ESCOLA', 'IGREJA', 'CENTRO_COMUNITARIO', 'UBS', 'OUTRO')),
    CONSTRAINT CK_AE_PONTO_SITUACAO CHECK (DS_SITUACAO IN ('ATIVO', 'INATIVO')),
    CONSTRAINT CK_AE_PONTO_CAPACIDADE CHECK (NR_CAPACIDADE > 0)
);

CREATE TABLE TB_AE_MORADOR (
    ID_MORADOR               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NM_MORADOR               VARCHAR(120) NOT NULL,
    DS_EMAIL                 VARCHAR(150) NOT NULL,
    NR_CPF                   VARCHAR(11)  NOT NULL,
    NR_TELEFONE              VARCHAR(20)  NOT NULL,
    DS_ENDERECO              VARCHAR(200) NOT NULL,
    NR_LATITUDE              DECIMAL(9,6),
    NR_LONGITUDE             DECIMAL(9,6),
    ID_SETOR                 BIGINT       NOT NULL,
    DS_NECESSIDADE_ESPECIAL  VARCHAR(25)  NOT NULL,
    DS_PUSH_TOKEN            VARCHAR(200),
    DT_CRIACAO               TIMESTAMP    NOT NULL,
    CONSTRAINT PK_AE_MORADOR PRIMARY KEY (ID_MORADOR),
    CONSTRAINT UK_AE_MORADOR_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT UK_AE_MORADOR_CPF UNIQUE (NR_CPF),
    CONSTRAINT FK_AE_MORADOR_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_AE_SETOR (ID_SETOR),
    CONSTRAINT CK_AE_MORADOR_NECESSIDADE CHECK (DS_NECESSIDADE_ESPECIAL IN
        ('NENHUMA', 'IDOSO', 'MOBILIDADE_REDUZIDA', 'DEFICIENCIA_VISUAL', 'DEFICIENCIA_AUDITIVA', 'OUTRA'))
);
